-- Los IDs operativos son enteros asignados por PostgreSQL.
-- usuario conserva UUID para una futura integración uno-a-uno con Supabase Auth.
do $$
begin
  if exists (select 1 from public.categoria)
    or exists (select 1 from public.carta)
    or exists (select 1 from public.mesas)
    or exists (select 1 from public.pedido)
    or exists (select 1 from public.detalle_pedido) then
    raise exception 'La conversión de IDs solo puede ejecutarse antes de cargar datos operativos.';
  end if;
end;
$$;

alter table public.carta drop constraint carta_categoria_id_fkey;
